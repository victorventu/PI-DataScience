"""# Data Mining e Machine Learning

Para o projeto, utilizamos a **Regressão** _(para prever a demanda mensal e auxiliar na reposição de estoque)_ e no **Agrupamento** _(para entender o perfil de compra dos clientes)_.

A classificação, embora útil, não foi incluída pois as duas técnicas selecionadas já respondem integralmente à pergunta central de negócio do projeto: "Como prever a demanda mensal por produto e identificar o comportamento de compra dos produtores rurais para otimizar a reposição de estoque, evitando rupturas em períodos de alta e sobras de estoque na F.C.A. Serviços Pecuários?"
"""

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.pipeline import Pipeline
