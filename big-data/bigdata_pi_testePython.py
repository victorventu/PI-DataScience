"""# Operações OLAP

O cubo OLAP é formado por **três dimensões** e uma **medida**. No nosso cubo as dimensões são **Ano**, **Grupo de Produto** e **Trimestre**, e a medida é a **Receita**. Cada bolinha do gráfico é uma "célula" do cubo (uma combinação de ano, grupo e trimestre). Quanto maior e mais clara a bolinha, maior a receita.
"""

# Cubo OLAP: busca no Data Warehouse a receita de cada combinação de Ano, Grupo e Trimestre
consulta_cubo = '''
    SELECT t.Ano, p.Grupo, t.Trimestre,
           SUM(f."Total Líquido") AS Receita,
           COUNT(DISTINCT f."Nº Ped.") AS Pedidos
    FROM fato_vendas f
    JOIN dim_tempo t ON f.id_tempo = t.id_tempo
    JOIN dim_produto p ON f.IdProduto = p.IdProduto
    GROUP BY t.Ano, p.Grupo, t.Trimestre
'''
cubo = pd.read_sql_query(consulta_cubo, conn)

print(f"O cubo tem {len(cubo)} células ({cubo['Ano'].nunique()} anos x {cubo['Grupo'].nunique()} grupos x {cubo['Trimestre'].nunique()} trimestres)")
cubo.head()

# Gráfico do Cubo OLAP (3D)
# Grupos em ordem de receita (o grupo com mais receita fica em uma ponta do cubo)
