# Carregando os Dados Limpos (recarregando para garantir que estamos partindo do mesmo ponto)
df_ml = pd.read_csv('/content/drive/MyDrive/PI_DataScience/Gerador/vendas_limpa.csv', sep=';', parse_dates=['Dt.Ped.'])
print(f"Base carregada: {len(df_ml):,} linhas | de {df_ml['Dt.Ped.'].min():%d/%m/%Y} até {df_ml['Dt.Ped.'].max():%d/%m/%Y}")

"""## Modelo de Regressão - Random Forest (Previsão de Demanda)

**O que queremos prever:** a demanda mensal (soma da `Qnt.`) de cada produto.

**Variáveis usadas:** o produto, o ano, o mês, a demanda do mês anterior (`Lag_1`), a demanda do mesmo mês no ano anterior (`Lag_12`) e a média dos 3 meses anteriores (`Media_Movel_3`).

> Não usamos o valor vendido (`Total Líquido`) do próprio mês, porque esse valor só fica conhecido quando o mês acaba e já tem a quantidade dentro dele. Se usássemos, o modelo "colaria" a resposta e o resultado ficaria bom demais.

**Treino e teste:** separamos pelo tempo. Treino de 2016 a 2024 e teste de 2025 até outubro de 2026, como se estivéssemos prevendo o mês seguinte.
"""

# Engenharia de Variáveis para Regressão (Agrupando a demanda por mês e produto)
df_ml['Ano_Mes'] = df_ml['Dt.Ped.'].dt.to_period('M')
mensal = df_ml.groupby(['Ano_Mes', 'IdProduto'])['Qnt.'].sum().rename('Demanda_Mensal').reset_index()

# Tabela completa com todos os meses e todos os produtos (mês sem venda = demanda zero)
meses = pd.period_range(df_ml['Ano_Mes'].min(), df_ml['Ano_Mes'].max(), freq='M')
produtos = sorted(df_ml['IdProduto'].unique())
grade = pd.MultiIndex.from_product([meses, produtos], names=['Ano_Mes', 'IdProduto']).to_frame(index=False)
df_regressao = grade.merge(mensal, on=['Ano_Mes', 'IdProduto'], how='left').fillna({'Demanda_Mensal': 0})
df_regressao = df_regressao.sort_values(['IdProduto', 'Ano_Mes']).reset_index(drop=True)

df_regressao['Ano'] = df_regressao['Ano_Mes'].dt.year
df_regressao['Mes'] = df_regressao['Ano_Mes'].dt.month

# Histórico de cada produto (sempre de meses que já passaram)
demanda_produto = df_regressao.groupby('IdProduto')['Demanda_Mensal']
df_regressao['Lag_1'] = demanda_produto.shift(1)
df_regressao['Lag_12'] = demanda_produto.shift(12)
df_regressao['Media_Movel_3'] = demanda_produto.transform(lambda s: s.shift(1).rolling(3).mean())

# Tira os primeiros meses, que ainda não têm histórico
df_regressao = df_regressao.dropna(subset=['Lag_1', 'Lag_12', 'Media_Movel_3']).reset_index(drop=True)
print(f"Linhas (produto x mês) usadas no modelo: {len(df_regressao):,}")
df_regressao.head()

# Preparação para Treino e Teste (Regressão)
# Separamos os dados pelo tempo, como orientado, para simular uma previsão real
variaveis_num = ['Ano', 'Mes', 'Lag_1', 'Lag_12', 'Media_Movel_3']
variaveis_cat = ['IdProduto']

X_reg = df_regressao[variaveis_num + variaveis_cat]
y_reg = df_regressao['Demanda_Mensal']

# Divisão Temporal: Treino (2016-2024), Teste (2025-2026)
treino_mask = df_regressao['Ano'] <= 2024
X_train_reg, y_train_reg = X_reg[treino_mask], y_reg[treino_mask]
X_test_reg, y_test_reg = X_reg[~treino_mask], y_reg[~treino_mask]

print(f"Treino: {len(X_train_reg):,} linhas | Teste: {len(X_test_reg):,} linhas")

# Pipeline de Processamento (StandardScaler nos números e OneHotEncoder no produto)
preprocessor_reg = ColumnTransformer(transformers=[
    ('num', Pipeline(steps=[('imputer', SimpleImputer(strategy='median')),
                            ('scaler', StandardScaler())]), variaveis_num),
    ('cat', OneHotEncoder(handle_unknown='ignore'), variaveis_cat),
])

# Criação e Treinamento do Modelo Random Forest
model_rf = RandomForestRegressor(n_estimators=200, random_state=42, n_jobs=-1)

pipeline_reg = Pipeline(steps=[
    ('preprocessor', preprocessor_reg),
    ('regressor', model_rf)
])

pipeline_reg.fit(X_train_reg, y_train_reg)

# Avaliação do Modelo (comparando com duas previsões simples)
def avaliar(y_real, y_prev):
    return {
        'MAE': mean_absolute_error(y_real, y_prev),
        'RMSE': np.sqrt(mean_squared_error(y_real, y_prev)),
        'R²': r2_score(y_real, y_prev),
        'Erro (% da demanda)': np.abs(y_real - y_prev).sum() / y_real.sum() * 100,
    }

y_pred_reg = pipeline_reg.predict(X_test_reg)

# Previsão simples 1: repetir a demanda do mesmo mês do ano anterior
previsao_ano_anterior = X_test_reg['Lag_12']

# Previsão simples 2: média do produto naquele mês (calculada só com o treino)
media_mes = df_regressao[treino_mask].groupby(['IdProduto', 'Mes'])['Demanda_Mensal'].mean()
previsao_media = df_regressao[~treino_mask].apply(lambda r: media_mes.get((r['IdProduto'], r['Mes']), np.nan), axis=1)

comparacao = pd.DataFrame({
    'Random Forest': avaliar(y_test_reg, y_pred_reg),
    'Mesmo mês do ano anterior': avaliar(y_test_reg, previsao_ano_anterior),
    'Média histórica do mês': avaliar(y_test_reg, previsao_media),
}).T.round(2)

print("--- Avaliação do Modelo de Regressão (Random Forest) ---")
display(comparacao)

erro_rf = comparacao.loc['Random Forest', 'Erro (% da demanda)']
print(f"\nO modelo erra em média {erro_rf:.1f}% da demanda real nos {len(y_test_reg)} meses de teste.")

# O Random Forest é adequado pois consegue capturar relações não-lineares, como a sazonalidade e o histórico de cada produto.

# Quais variáveis mais ajudaram o modelo?
nomes = pipeline_reg.named_steps['preprocessor'].get_feature_names_out()
importancias = pd.Series(pipeline_reg.named_steps['regressor'].feature_importances_, index=nomes)
importancias.index = [n.replace('num__', '').replace('cat__', '') for n in importancias.index]
print("Variáveis mais importantes:")
print(importancias.sort_values(ascending=False).head(6).round(3))

