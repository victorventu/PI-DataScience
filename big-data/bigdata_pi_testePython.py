# Hadoop: Papel do HDFS, YARN, MapReduce e Hive na arquitetura

# - HDFS: Armazenamento distribuído. Guarda os arquivos brutos de vendas da F.C.A. distribuindo-os em blocos para evitar perda de dados.
# - Hive: Funciona como um Data Warehouse no ecossistema, permitindo usar SQL para consultar dados no HDFS.
# - MapReduce: Processamento em lotes dividido em mapeamento, embaralhamento e redução.
# - YARN: Gerenciador de recursos que orquestra a fila e a execução das tarefas (jobs) no cluster.


# MAPREDUCE - Contar a quantidade de vendas realizadas por Estado (demanda regional)
def mapper_fca(linhas):
    # Mapper: identifica o estado de cada venda e cria o par (Estado, 1)
    pares = []
    for linha in linhas:
        if pd.notna(linha):
            pares.append((str(linha).strip(), 1))
    return pares

def shuffle_fca(mapped_data):
    # Shuffle: agrupa todas as ocorrências de cada Estado
    agrupado = {}
    for chave, valor in mapped_data:
        if chave not in agrupado:
            agrupado[chave] = []
        agrupado[chave].append(valor)
    return agrupado

def reducer_fca(agrupado):
    # Reducer: processa o agrupamento somando os totais
    return {chave: sum(valores) for chave, valores in agrupado.items()}

# Executando a simulação do MapReduce com a coluna 'Estado'
dados_entrada = df_ml['Estado'].dropna().tolist()
mapeado = mapper_fca(dados_entrada)
agrupado = shuffle_fca(mapeado)
resultado_mr = reducer_fca(agrupado)

print("[MapReduce] Quantidade de itens com nota fiscal por Estado (só os itens com NF têm Estado):")
print(resultado_mr)
print("-" * 50)

